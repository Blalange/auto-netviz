// LookupVendor returns the IEEE OUI manufacturer name if recognized.
func LookupVendor(mac string) string {
	norm, err := NormalizeMAC(mac)
	if err != nil {
		return ""
	}
	prefix := strings.ToUpper(norm[:8])
	return ouiVendors[prefix]
}
